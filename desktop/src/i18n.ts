export function normLang(v: unknown): Lang {
  if (typeof v === "string") {
    const c = v.toLowerCase().replace(/[^a-z]/g, "").slice(0, 2);
    if (c === "en" || c === "fr" || c === "it" || c === "de" || c === "es" || c === "pl" || c === "ru") return c;
  }
  return "en";
}

