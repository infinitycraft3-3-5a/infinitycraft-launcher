export function t(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  let s = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

